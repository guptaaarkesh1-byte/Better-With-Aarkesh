export const getCuratedArticle = (slugOrId) => {
  if (!slugOrId) return CURATED_LIBRARY_ARTICLES[0];
  const query = slugOrId.toLowerCase().trim();
  const found = CURATED_LIBRARY_ARTICLES.find(
    a => a.id === query || a.slug === query || a.title.toLowerCase().includes(query)
  );
  return found || CURATED_LIBRARY_ARTICLES[0];
};
